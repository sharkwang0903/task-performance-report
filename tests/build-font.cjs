// Rebuild the local-file-compatible PDF font bundle after changing the licensed TTF.
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../docs/fonts');
const font=fs.readFileSync(path.join(root,'NotoSansTC-Regular.ttf'));
fs.writeFileSync(path.join(root,'report-font.js'),'/* Noto Sans TC Regular - SIL OFL; see OFL.txt. Generated by tests/build-font.cjs. */\nwindow.ReportFontBase64="'+font.toString('base64')+'";\n');
console.log('Built local PDF font bundle.');
